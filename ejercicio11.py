dinero_ahorro = int(input("Introduce la cantidad de dinero que ahorras cada año: "))
primer_año = dinero_ahorro * (1 + 0.04)
segundo_año = primer_año * (1 + 0.04)
tercer_año = segundo_año * (1 + 0.04)
